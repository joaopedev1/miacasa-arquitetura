// Generates src/data/properties.ts from cloudinary_map.json.
// One folder (top-level under FOTOS_OBRA) = one obra. Cover = first image alphabetically.
import { readFileSync, writeFileSync } from "node:fs";

const map = JSON.parse(readFileSync("cloudinary_map.json", "utf8"));

// Group by top-level folder
const byFolder = {};
for (const [rel, info] of Object.entries(map)) {
  const top = rel.split("/")[0];
  (byFolder[top] ||= []).push({ rel, ...info });
}

// Order folders alphabetically, sort images within each folder by filename
const folders = Object.keys(byFolder).sort();
for (const f of folders) {
  byFolder[f].sort((a, b) => a.rel.localeCompare(b.rel, "pt", { numeric: true }));
}

// Human-friendly title from folder name
const titleize = (name) =>
  name
    .replace(/_/g, " ")
    .toLowerCase()
    .replace(/\b\w/g, (c) => c.toUpperCase());

// Deliver a Cloudinary-transformed URL (auto format + quality, max width 1600)
const cldUrl = (publicId) =>
  `https://res.cloudinary.com/sccu8xvd/image/upload/f_auto,q_auto:good,w_1600/${publicId}`;

const obras = folders.map((f, idx) => {
  const imgs = byFolder[f].map((i) => cldUrl(i.public_id));
  return {
    id: `obra-${idx + 1}`,
    title: `Residencial ${titleize(f)}`,
    status: "Concluído",
    category: "Residencial",
    cover: imgs[0],
    images: imgs,
  };
});

// Hero: 1 cover per folder, up to 5
const hero = obras.slice(0, 5).map((o) => o.cover);

const src = `export interface Property {
  id: string;
  title: string;
  status: "Concluído" | "Em andamento";
  category: "Residencial" | "Interiores";
  cover: string;
  images: string[];
}

// Generated by scripts/rewrite-properties.mjs from cloudinary_map.json.
// Do not hand-edit unless you're OK losing changes on the next regeneration.
export const properties: Property[] = ${JSON.stringify(obras, null, 2)};

export const heroImages = ${JSON.stringify(hero, null, 2)};
`;

writeFileSync("src/data/properties.ts", src);
console.log(`Wrote ${obras.length} obras (${obras.reduce((s, o) => s + o.images.length, 0)} images total).`);
